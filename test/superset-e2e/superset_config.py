"""superset_config.py for the local e2e stack — MCP settings only.

The image ships its complete config (Postgres/Redis/Celery/OAuth) at
`/app/pythonpath/superset_config.base.py`; this file exec's it first so the stack
keeps working, then adds only the MCP block documented in
docs/librechat-integrations.md section 1.

Every MCP claim here was verified against the apache/superset 6.1.0 tag. In
particular MCP_DISABLED_TOOLS is deliberately NOT set: it does not exist in that
tag, so setting it would be a silent no-op and would imply a control that is not
there.
"""
import os

_BASE = os.environ.get(
    "SUPERSET_BASE_CONFIG", "/app/pythonpath/superset_config.base.py"
)
if os.path.exists(_BASE):
    with open(_BASE, encoding="utf-8") as _handle:
        exec(compile(_handle.read(), _BASE, "exec"), globals())

# ---- MCP ------------------------------------------------------------------
MCP_AUTH_ENABLED = True
MCP_JWT_ALGORITHM = "HS256"
MCP_JWT_SECRET = os.environ["MCP_JWT_SECRET"]
MCP_JWT_ISSUER = "superset"
MCP_JWT_AUDIENCE = "superset"
MCP_DEV_USERNAME = os.environ.get("MCP_DEV_USERNAME", "librechat-agent")
MCP_REQUIRED_SCOPES = "mcp:read"   # global JWT admission gate, not per-tool
MCP_RBAC_ENABLED = True

# Public origin for links generated by MCP tools (chart previews, SQL Lab URLs).
SUPERSET_WEBSERVER_ADDRESS = "http://127.0.0.1:18088"
WEBDRIVER_BASEURL = "http://127.0.0.1:18088/"
WEBDRIVER_BASEURL_USER_FRIENDLY = "http://127.0.0.1:18088/"

# Keep the shipped discovery defaults: BM25, only health_check and
# get_instance_info pinned. Note that enabled=False already exposes the full
# catalog on this tag; the native/compact listing knobs are a later addition.
MCP_TOOL_SEARCH_CONFIG = {
    "enabled": True,
    "strategy": "bm25",
    "max_results": 5,
    "always_visible": ["health_check", "get_instance_info"],
    "include_schemas": False,
}
